/**
 * Writes typed `as const` ABIs (and AgentProxy bytecode) into sdk/src/abi.ts so the SDK, relay,
 * bots and arena all share one source of truth. Run after `hardhat compile`.
 */
import * as fs from "fs";
import * as path from "path";
import { artifacts } from "hardhat";

const NAMES = ["Vault", "Firewall", "Arena", "Lineage", "Crucible", "AgentProxy", "PolicyGuard", "GuardedAccount", "MockIdentityRegistry"];

async function main() {
  let out = "/* eslint-disable */\n// AUTO-GENERATED by contracts/scripts/export-abi.ts — do not edit.\n\n";
  for (const n of NAMES) {
    const a = await artifacts.readArtifact(n);
    const name = n[0].toLowerCase() + n.slice(1);
    out += `export const ${name}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n\n`;
    if (n === "AgentProxy" || n === "PolicyGuard" || n === "GuardedAccount") {
      out += `export const ${name}Bytecode = ${JSON.stringify(a.bytecode)} as \`0x\${string}\`;\n\n`;
    }
  }
  const target = path.resolve(__dirname, "../../sdk/src/abi.ts");
  fs.writeFileSync(target, out);
  console.log(`wrote ${target}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
