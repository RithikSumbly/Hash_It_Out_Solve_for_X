// The visitor's microphone, for an audience with the queen (lib/audience.ts): passes the raw samples to the page
// in blocks of 2048. Nothing is recorded until the visitor presses to speak; nothing is kept in the browser.
class RqMic extends AudioWorkletProcessor {
  constructor() {
    super();
    this.buf = new Float32Array(2048);
    this.n = 0;
  }
  process(inputs) {
    const ch = inputs[0] && inputs[0][0];
    if (ch) {
      for (let i = 0; i < ch.length; i++) {
        this.buf[this.n++] = ch[i];
        if (this.n === this.buf.length) {
          this.port.postMessage(this.buf.slice(0));
          this.n = 0;
        }
      }
    }
    return true;
  }
}
registerProcessor("rq-mic", RqMic);
